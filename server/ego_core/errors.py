CATALOG = {code: {'message': v[0], 'hint': v[1], 'message_en': v[2], 'hint_en': v[3]} for code, v in _E.items()}


def describe(code, lang=None):
    """(message, hint) for a code in ru/en/fr/es/de (default: the current request's language);
    unknown codes get a safe generic text with the code."""
    from server.ego_core import languages
    lang = languages.normalize(lang) or languages.current()
    entry = CATALOG.get(code)
    if entry is None:
        generic = {'ru': (f'Ошибка {code}.', 'Подробности — в диагностике.'),
                   'fr': (f'Erreur {code}.', 'Voir le diagnostic.'),
                   'es': (f'Error {code}.', 'Consulta el diagnóstico.'),
                   'de': (f'Fehler {code}.', 'Siehe Diagnose.')}
        return generic.get(lang, (f'Error {code}.', 'See diagnostics for details.'))
    if lang == 'ru':
        return entry['message'], entry['hint']
    if lang in ('fr', 'es', 'de'):
        from server.ego_core.errors_i18n import TEXTS
        if code in TEXTS[lang]:
            return TEXTS[lang][code]
    return entry['message_en'], entry['hint_en']
