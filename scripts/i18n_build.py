"""Build client dictionaries from i18n/client/*.tsv into client/js/i18n/<lang>.js.

Each TSV line: Russian<TAB>English<TAB>French<TAB>Spanish<TAB>German. Lines starting
with # are comments. Reports Russian strings of the client that have no translation.

    .venv\\Scripts\\python.exe scripts\\i18n_extract.py
    .venv\\Scripts\\python.exe scripts\\i18n_build.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'i18n' / 'client'
OUT = ROOT / 'client' / 'js' / 'i18n'
LANGS = ('en', 'fr', 'es', 'de')
# Strings that are not shown in the page: model instructions and template texts
# (translated with the model language, see server/ego_core/languages.py).
NOT_UI = ()
# Pieces of strings that are glued in code; the whole sentence is a pattern in the TSV.
GLUED = {'»? Персонажи и чаты не будут удалены.', 'Удалить мир «', '. Он действует 10 минут.', 'А',
         'disabled title="Доступ к историям выключен"',
         '» подставлен — поправь под себя и создай мир', '» подставлен — поправь под себя и сохрани',
         'Заменить уже заполненные поля шаблоном «', 'Шаблон «'}


def load():
    rows = {}
    for path in sorted(SOURCE.glob('*.tsv')):
        for number, line in enumerate(path.read_text(encoding='utf-8').splitlines(), 1):
            if not line.strip() or line.startswith('#'):
                continue
            cells = line.split('\t')
            if len(cells) != 5 or not all(c.strip() for c in cells):
                raise SystemExit(f'{path.name}:{number}: need 5 non-empty columns, got {len(cells)}')
            ru = cells[0].strip()
            holes = set(re.findall(r'\{\d+\}', ru))
            for lang, cell in zip(LANGS, cells[1:]):
                if set(re.findall(r'\{\d+\}', cell)) != holes:
                    raise SystemExit(f'{path.name}:{number}: placeholders differ in {lang}')
            rows[ru] = [c.strip() for c in cells[1:]]
    return rows


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    rows = load()
    for index, lang in enumerate(LANGS):
        data = {ru: values[index] for ru, values in rows.items()}
        text = ('/* Generated by scripts/i18n_build.py from i18n/client/*.tsv. Do not edit. */\n'
                'window.EGOI18n && EGOI18n.install(' + json.dumps(data, ensure_ascii=False, indent=0) + ');\n')
        (OUT / f'{lang}.js').write_text(text, encoding='utf-8', newline='\n')
    strings = json.loads((OUT / 'strings.json').read_text(encoding='utf-8'))
    missing = [k for k, f in strings.items() if f not in NOT_UI and k not in rows and k not in GLUED]
    print(f'{len(rows)} translated strings -> {", ".join(LANGS)}; untranslated UI strings: {len(missing)}')
    for k in missing[:int(sys.argv[1]) if len(sys.argv) > 1 else 40]:
        print('  ', strings[k], '|', k)


if __name__ == '__main__':
    main()
